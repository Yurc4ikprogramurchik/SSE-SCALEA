function setLanguage(lang) {

    if (!translations[lang]) {
        lang = "ru";
    }

    currentLang = lang;

    localStorage.setItem(
        "lang",
        lang
    );


    /* ===== HTML LANG ===== */

    document.documentElement.lang =
        lang;


    /* ===== SEO FOR CURRENT PAGE ===== */

    const page =
        document.body.dataset.page || "home";

    const seo =
        pageSEO[page] &&
        pageSEO[page][lang];

    if (seo) {

        document.title =
            seo.title;


        const metaDescription =
            document.querySelector(
                'meta[name="description"]'
            );

        if (metaDescription) {

            metaDescription.setAttribute(
                "content",
                seo.description
            );

        }


        const ogTitle =
            document.querySelector(
                'meta[property="og:title"]'
            );

        if (ogTitle) {

            ogTitle.setAttribute(
                "content",
                seo.title
            );

        }


        const ogDescription =
            document.querySelector(
                'meta[property="og:description"]'
            );

        if (ogDescription) {

            ogDescription.setAttribute(
                "content",
                seo.description
            );

        }

    }


    /* ===== TEXTS ===== */

    document
        .querySelectorAll("[data-i18n]")
        .forEach(el => {

            const key =
                el.dataset.i18n;

            if (
                translations[lang] &&
                translations[lang][key] !== undefined
            ) {

                el.textContent =
                    translations[lang][key];

            }

        });


    /* ===== IMAGES ===== */

    document
        .querySelectorAll("[data-i18n-img]")
        .forEach(el => {

            const key =
                el.dataset.i18nImg;

            if (
                translations[lang] &&
                translations[lang][key]
            ) {

                el.src =
                    translations[lang][key];

            }

        });


    /* ===== IMAGE ALT ===== */

    document
        .querySelectorAll("[data-i18n-alt]")
        .forEach(el => {

            const key =
                el.dataset.i18nAlt;

            if (
                translations[lang] &&
                translations[lang][key]
            ) {

                el.alt =
                    translations[lang][key];

            }

        });


    /* ===== LANGUAGE BUTTON ===== */

    document
        .querySelectorAll(".lang-btn")
        .forEach(btn => {

            btn.classList.toggle(
                "active",
                btn.dataset.lang === lang
            );

        });


    /* ===== CATALOG PRODUCTS ===== */

    if (
        typeof renderProducts === "function"
    ) {

        const urlParams =
            new URLSearchParams(
                window.location.search
            );

        const category =
            urlParams.get("category") || "all";

        const subcategory =
            urlParams.get("subcategory") || null;

        renderProducts(
            category,
            subcategory
        );

    }

}


